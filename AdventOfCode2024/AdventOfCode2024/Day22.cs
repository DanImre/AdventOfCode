using System.Net.Http.Headers;

namespace AdventOfCode2024
{
    public class Day22 : IDay
    {
        public string InputPath { get; set; } = "day22Input.txt";
        //public string InputPath { get; set; } = "day22TestInput.txt";
        //public string InputPath { get; set; } = "day22TestInput2.txt";

        private long Mix(long secret, long num) => secret ^ num;
        private long Prune(long secret) => secret % 16777216;
        private long Evolve(long secret)
        {
            long stepone = secret * 64;
            secret = Prune(Mix(secret, stepone));

            long steptwo = secret / 32;
            secret = Prune(Mix(secret, steptwo));

            long stepthree = secret * 2048;
            secret = Prune(Mix(secret, stepthree));

            return secret;
        }

        public void PartOne()
        {
            string[] s = File.ReadAllLines(InputPath);

            long solution = 0;
            foreach (var item in s)
            {
                long secret = long.Parse(item);
                for (int i = 0; i < 2000; i++)
                    secret = Evolve(secret);

                solution += secret;
            }

            // For the test it should be: 37327623
            // 14119253575
            Console.WriteLine($"The sum of the 2000th secret number generated by each buyer is: {solution}!");
        }


        public void PartTwo()
        {
            (int first, int second, int third, int forth) getSteps(Queue<int> q)
            {
                int[] arr = [.. q];
                return (arr[0], arr[1], arr[2], arr[3]);
            }

            string[] s = File.ReadAllLines(InputPath);

            Dictionary<(int first, int second, int third, int forth), int> seqCount = [];
            foreach (var item in s)
            {
                HashSet<(int first, int second, int third, int forth)> buyerSeqs = [];
                long secret = long.Parse(item);
                Queue<int> seq = [];
                for (int i = 0; i < 3; i++)
                {
                    long evolved = Evolve(secret);
                    int priceChange = (int)((evolved % 10) - (secret % 10));
                    seq.Enqueue(priceChange);
                    secret = evolved;
                }

                for (int i = 3; i < 2000; i++)
                {
                    long evolved = Evolve(secret);

                    int price = (int)(evolved % 10);
                    int priceChange = (int)((evolved % 10) - (secret % 10));

                    seq.Enqueue(priceChange);
                    var steps = getSteps(seq);

                    if (buyerSeqs.Add(steps))
                    {
                        if (!seqCount.TryAdd(steps, price))
                            seqCount[steps] += price;
                    }
                    secret = evolved;

                    seq.Dequeue();
                }
            }

            var chosenSeq = seqCount.MaxBy(x => x.Value).Key;
            Console.WriteLine(chosenSeq);
            long solution = seqCount.Max(x => x.Value);

            // For the test 2 it should be: 23
            // 1600
            Console.WriteLine($"The most bananas you can get is: {solution}!");
        }
    }
}
